export function bulletFamilyFor(role: string): BulletFamilyKey {
  const value = role.trim().toLowerCase();
  if (!value) return "general";
  if (/\bintern\b|trainee|apprentice/.test(value) && !/internal/.test(value)) {
    const field = value.replace(/\b(intern|trainee|apprentice)\b/g, "").trim();
    const domain = FAMILY_RULES.find(([key, rule]) => key !== "intern" && rule.test(field));
    return domain ? domain[0] : "intern";
  }
  const match = FAMILY_RULES.find(([, rule]) => rule.test(value));
  return match ? match[0] : "general";
}

export function fallbackBulletSuggestions(role: string): { family: BulletFamily; bullets: string[] } {
  const family = BULLET_FAMILIES[bulletFamilyFor(role)];
  return { family, bullets: family.bullets };
}
