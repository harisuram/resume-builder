/** Shared catalog matching: hide already-chosen values, then filter by the
 * draft. Prefix matches float to the top once the user is typing. */
export function filterCatalog(catalog: string[], query: string, selected: string[] = []): string[] {
  const taken = new Set(selected.map((value) => value.toLowerCase()));
  const needle = query.trim().toLowerCase();
  const matches = catalog.filter((item) => {
    if (taken.has(item.toLowerCase())) return false;
    if (!needle) return true;
    return item.toLowerCase().includes(needle);
  });
  if (!needle) return matches;
  return matches.sort((a, b) => {
    const aName = a.toLowerCase();
    const bName = b.toLowerCase();
    const aPrefix = aName.startsWith(needle);
    const bPrefix = bName.startsWith(needle);
    if (aPrefix !== bPrefix) return aPrefix ? -1 : 1;
    return a.localeCompare(b, "en", { sensitivity: "base" });
  });
}

function uniqueSorted(items: string[]): string[] {
  return [...new Set(items)].sort((a, b) => a.localeCompare(b, "en", { sensitivity: "base" }));
}

